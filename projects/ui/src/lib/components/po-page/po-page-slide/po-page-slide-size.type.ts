/**
 * @usedBy PoPageSlide
 *
 * @description
 *
 * Define os tamanhos válidos para a largura do `po-page-slide`.
 *
 * Valores válidos:
 *  - `sm`: pequeno.
 *  - `md`: médio (padrão).
 *  - `lg`: grande.
 *  - `xl`: extra-grande.
 *  - `auto`: automático.
 *  - `full`: ocupa 100% da largura da tela e oculta o overlay de fundo.
 */
export type PoPageSlideSize = 'sm' | 'md' | 'lg' | 'xl' | 'auto' | 'full';

import { DEPRECATED_THEME_COMMENT, injectDeprecatedTheme } from './theme-bootstrap-migration';

const lines = (...content: Array<string>) => content.join('\n');

describe('v22 theme-deprecated injectDeprecatedTheme:', () => {
  it('should inject the service and create a constructor (component generated by ng new)', () => {
    const source = lines(
      `import { Component, signal } from '@angular/core';`,
      `import { RouterOutlet } from '@angular/router';`,
      ``,
      `@Component({`,
      `  selector: 'app-root',`,
      `  imports: [RouterOutlet],`,
      `  templateUrl: './app.html',`,
      `  styleUrl: './app.css'`,
      `})`,
      `export class App {`,
      `  protected readonly title = signal('my-app');`,
      `}`,
      ``
    );

    const result = injectDeprecatedTheme(source, 'App');

    expect(result.changed).toBe(true);
    expect(result.content).toBe(
      lines(
        `import { Component, signal, inject } from '@angular/core';`,
        `import { RouterOutlet } from '@angular/router';`,
        `import { PoThemeService, poThemeDefaultDeprecated } from '@po-ui/ng-components';`,
        ``,
        `@Component({`,
        `  selector: 'app-root',`,
        `  imports: [RouterOutlet],`,
        `  templateUrl: './app.html',`,
        `  styleUrl: './app.css'`,
        `})`,
        `export class App {`,
        `  private readonly poThemeService = inject(PoThemeService);`,
        ``,
        `  protected readonly title = signal('my-app');`,
        ``,
        `  constructor() {`,
        `    ${DEPRECATED_THEME_COMMENT}`,
        `    this.poThemeService.setTheme(poThemeDefaultDeprecated);`,
        `  }`,
        `}`,
        ``
      )
    );
    expect(result.warnings).toEqual([]);
  });

  it('should handle an empty component class', () => {
    const source = lines(
      `import { Component } from '@angular/core';`,
      `@Component({ selector: 'app-root', template: '' })`,
      `export class AppComponent {}`
    );

    expect(injectDeprecatedTheme(source).content).toBe(
      lines(
        `import { Component, inject } from '@angular/core';`,
        `import { PoThemeService, poThemeDefaultDeprecated } from '@po-ui/ng-components';`,
        `@Component({ selector: 'app-root', template: '' })`,
        `export class AppComponent {`,
        `  private readonly poThemeService = inject(PoThemeService);`,
        ``,
        `  constructor() {`,
        `    ${DEPRECATED_THEME_COMMENT}`,
        `    this.poThemeService.setTheme(poThemeDefaultDeprecated);`,
        `  }`,
        `}`
      )
    );
  });

  it('should create the constructor before methods when there are no properties', () => {
    const source = lines(
      `import { Component } from '@angular/core';`,
      `@Component({ selector: 'app-root', template: '' })`,
      `export class AppComponent {`,
      `  run() {}`,
      `}`
    );

    expect(injectDeprecatedTheme(source).content).toBe(
      lines(
        `import { Component, inject } from '@angular/core';`,
        `import { PoThemeService, poThemeDefaultDeprecated } from '@po-ui/ng-components';`,
        `@Component({ selector: 'app-root', template: '' })`,
        `export class AppComponent {`,
        `  private readonly poThemeService = inject(PoThemeService);`,
        ``,
        `  constructor() {`,
        `    ${DEPRECATED_THEME_COMMENT}`,
        `    this.poThemeService.setTheme(poThemeDefaultDeprecated);`,
        `  }`,
        ``,
        `  run() {}`,
        `}`
      )
    );
  });

  it('should fill an empty constructor with parameters', () => {
    const source = lines(
      `import { Component } from '@angular/core';`,
      `import { Router } from '@angular/router';`,
      `@Component({ selector: 'app-root', template: '' })`,
      `export class AppComponent {`,
      `  constructor(private router: Router) {}`,
      `}`
    );

    expect(injectDeprecatedTheme(source).content).toBe(
      lines(
        `import { Component, inject } from '@angular/core';`,
        `import { Router } from '@angular/router';`,
        `import { PoThemeService, poThemeDefaultDeprecated } from '@po-ui/ng-components';`,
        `@Component({ selector: 'app-root', template: '' })`,
        `export class AppComponent {`,
        `  private readonly poThemeService = inject(PoThemeService);`,
        ``,
        `  constructor(private router: Router) {`,
        `    ${DEPRECATED_THEME_COMMENT}`,
        `    this.poThemeService.setTheme(poThemeDefaultDeprecated);`,
        `  }`,
        `}`
      )
    );
  });

  it('should insert the call at the start of an existing constructor body', () => {
    const source = lines(
      `import { Component } from '@angular/core';`,
      `@Component({ selector: 'app-root', template: '' })`,
      `export class AppComponent {`,
      `  constructor() {`,
      `    console.log('start');`,
      `  }`,
      `}`
    );

    expect(injectDeprecatedTheme(source).content).toBe(
      lines(
        `import { Component, inject } from '@angular/core';`,
        `import { PoThemeService, poThemeDefaultDeprecated } from '@po-ui/ng-components';`,
        `@Component({ selector: 'app-root', template: '' })`,
        `export class AppComponent {`,
        `  private readonly poThemeService = inject(PoThemeService);`,
        ``,
        `  constructor() {`,
        `    ${DEPRECATED_THEME_COMMENT}`,
        `    this.poThemeService.setTheme(poThemeDefaultDeprecated);`,
        `    console.log('start');`,
        `  }`,
        `}`
      )
    );
  });

  it('should insert the call right after super()', () => {
    const source = lines(
      `import { Component } from '@angular/core';`,
      `import { Base } from './base';`,
      `@Component({ selector: 'app-root', template: '' })`,
      `export class AppComponent extends Base {`,
      `  constructor() {`,
      `    super();`,
      `    this.init();`,
      `  }`,
      `}`
    );

    expect(injectDeprecatedTheme(source).content).toBe(
      lines(
        `import { Component, inject } from '@angular/core';`,
        `import { Base } from './base';`,
        `import { PoThemeService, poThemeDefaultDeprecated } from '@po-ui/ng-components';`,
        `@Component({ selector: 'app-root', template: '' })`,
        `export class AppComponent extends Base {`,
        `  private readonly poThemeService = inject(PoThemeService);`,
        ``,
        `  constructor() {`,
        `    super();`,
        `    ${DEPRECATED_THEME_COMMENT}`,
        `    this.poThemeService.setTheme(poThemeDefaultDeprecated);`,
        `    this.init();`,
        `  }`,
        `}`
      )
    );
  });

  it('should reuse existing imports of inject and PO UI', () => {
    const source = lines(
      `import { Component, inject as di } from '@angular/core';`,
      `import { PoMenuItem } from '@po-ui/ng-components';`,
      `@Component({ selector: 'app-root', template: '' })`,
      `export class AppComponent {`,
      `  readonly menus: Array<PoMenuItem> = [];`,
      `}`
    );

    expect(injectDeprecatedTheme(source).content).toBe(
      lines(
        `import { Component, inject as di } from '@angular/core';`,
        `import { PoMenuItem, PoThemeService, poThemeDefaultDeprecated } from '@po-ui/ng-components';`,
        `@Component({ selector: 'app-root', template: '' })`,
        `export class AppComponent {`,
        `  private readonly poThemeService = di(PoThemeService);`,
        ``,
        `  readonly menus: Array<PoMenuItem> = [];`,
        ``,
        `  constructor() {`,
        `    ${DEPRECATED_THEME_COMMENT}`,
        `    this.poThemeService.setTheme(poThemeDefaultDeprecated);`,
        `  }`,
        `}`
      )
    );
  });

  it('should pick the class informed by name', () => {
    const source = lines(
      `import { Component } from '@angular/core';`,
      `@Component({ selector: 'a', template: '' })`,
      `export class OtherComponent {}`,
      `@Component({ selector: 'app-root', template: '' })`,
      `export class AppComponent {}`
    );

    const content = injectDeprecatedTheme(source, 'AppComponent').content;

    expect(content).toContain(`export class OtherComponent {}`);
    expect(content).toContain(lines(`export class AppComponent {`, `  private readonly poThemeService`));
  });

  it('should be idempotent', () => {
    const source = lines(
      `import { Component } from '@angular/core';`,
      `@Component({ selector: 'app-root', template: '' })`,
      `export class AppComponent {}`
    );
    const first = injectDeprecatedTheme(source);

    const second = injectDeprecatedTheme(first.content);

    expect(first.changed).toBe(true);
    expect(second.changed).toBe(false);
    expect(second.content).toBe(first.content);
    expect(second.warnings).toEqual([]);
  });

  it('should warn without changes when there is no @Component class', () => {
    const source = lines(`import { NgModule } from '@angular/core';`, `@NgModule({})`, `export class AppModule {}`);

    const result = injectDeprecatedTheme(source);

    expect(result.changed).toBe(false);
    expect(result.content).toBe(source);
    expect(result.warnings.length).toBe(1);
    expect(result.warnings[0].reason).toContain('@Component');
  });

  it('should warn without changes when the class already has a poThemeService member', () => {
    const source = lines(
      `import { Component } from '@angular/core';`,
      `@Component({ selector: 'app-root', template: '' })`,
      `export class AppComponent {`,
      `  poThemeService = 1;`,
      `}`
    );

    const result = injectDeprecatedTheme(source);

    expect(result.changed).toBe(false);
    expect(result.warnings[0].reason).toContain('poThemeService');
  });
});
